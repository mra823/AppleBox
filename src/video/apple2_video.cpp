void Apple2Video::renderTextRow(std::span<const u8> ram,
                                const Apple2VideoState& st, int row) {
    const u16 base = textRowBase(st.page2, row);
    for (int col = 0; col < 40; ++col) {
        const u8 sc = ram[base + col];
        const u8 glyph = sc & 0x3f;
        // $00-$3F inverse, $40-$7F flash, $80-$FF normal.
        const bool inverse = sc < 0x40 || (sc < 0x80 && st.flash);
        for (int gy = 0; gy < 8; ++gy) {
            const u8 bits = gy < 7 ? kFont[glyph][gy] : 0;
            u32* dst = &fb_[(row * 8 + gy) * kWidth + col * 7];
            for (int gx = 0; gx < 7; ++gx) {
                // 5-pixel glyph centered in the 7-pixel cell.
                bool on = gx >= 1 && gx <= 5 && (bits >> (5 - gx)) & 1;
                if (inverse) on = !on;
                dst[gx] = on ? kWhite : kBlack;
            }
        }
    }
}

void Apple2Video::renderLoresRow(std::span<const u8> ram,
                                 const Apple2VideoState& st, int row) {
    const u16 base = textRowBase(st.page2, row);
    for (int col = 0; col < 40; ++col) {
        const u8 v = ram[base + col];
        const u32 top = kLores[v & 0x0f];
        const u32 bottom = kLores[v >> 4];
        for (int gy = 0; gy < 8; ++gy) {
            u32* dst = &fb_[(row * 8 + gy) * kWidth + col * 7];
            const u32 c = gy < 4 ? top : bottom;
            for (int gx = 0; gx < 7; ++gx) dst[gx] = c;
        }
    }
}

void Apple2Video::renderHiresRow(std::span<const u8> ram,
                                 const Apple2VideoState& st, int row) {
    // A text row covers 8 hires scanlines.
    for (int gy = 0; gy < 8; ++gy) {
        const int line = row * 8 + gy;
        const u16 base = hiresLineBase(st.page2, line);

        // Expand the 40 bytes into 280 dot bits + per-dot palette shift.
        bool bits[kWidth];
        bool shift[kWidth];
        for (int byte = 0; byte < 40; ++byte) {
            const u8 v = ram[base + byte];
            for (int i = 0; i < 7; ++i) {
                bits[byte * 7 + i] = (v >> i) & 1; // LSB is leftmost
                shift[byte * 7 + i] = v & 0x80;
            }
        }

        // Bit-pair artifact coloring: adjacent dots fuse to white; isolated
        // dots take the phase color (even/odd column), with the byte's high
        // bit selecting the violet/green vs blue/orange palette; a single
        // gap between two dots fills with the dots' phase color.
        u32* dst = &fb_[line * kWidth];
        for (int x = 0; x < kWidth; ++x) {
            const bool left = x > 0 && bits[x - 1];
            const bool right = x < kWidth - 1 && bits[x + 1];
            auto phaseColor = [&](int px) {
                const bool odd = px & 1;
                if (shift[x]) return odd ? kOrange : kBlue;
                return odd ? kGreen : kViolet;
            };
            if (bits[x])
                dst[x] = (left || right) ? kWhite : phaseColor(x);
            else
                dst[x] = (left && right) ? phaseColor(x + 1) : kBlack;
        }
    }
}

void Apple2Video::render(std::span<const u8> ram, const Apple2VideoState& st) {
    for (int row = 0; row < 24; ++row) {
        const bool textRow = st.text || (st.mixed && row >= 20);
        if (textRow)
            renderTextRow(ram, st, row);
        else if (st.hires)
            renderHiresRow(ram, st, row);
        else
            renderLoresRow(ram, st, row);
    }
}

u64 Apple2Video::frameHash() const {
    u64 h = 0xcbf29ce484222325ull; // FNV-1a 64
    for (u32 px : fb_) {
        for (int i = 0; i < 4; ++i) {
            h ^= (px >> (i * 8)) & 0xff;
            h *= 0x100000001b3ull;
        }
    }
    return h;
}

