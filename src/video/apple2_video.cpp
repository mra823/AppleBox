// Framebuffer pixel format is RGBA8888 in memory (R in the low byte), i.e.
// what glTexImage2D(GL_RGBA, GL_UNSIGNED_BYTE) expects on little-endian.
constexpr u32 rgb(u8 r, u8 g, u8 b) {
    return 0xff000000u | (static_cast<u32>(b) << 16) |
           (static_cast<u32>(g) << 8) | r;
}

