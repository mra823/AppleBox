constexpr u16 textRowBase(bool page2, int row) {
    return static_cast<u16>((page2 ? 0x0800 : 0x0400) + (row % 8) * 0x80 +
                            (row / 8) * 0x28);
}

constexpr u16 hiresLineBase(bool page2, int line) {
    return static_cast<u16>((page2 ? 0x4000 : 0x2000) + (line % 8) * 0x400 +
                            ((line / 8) % 8) * 0x80 + (line / 64) * 0x28);
}

